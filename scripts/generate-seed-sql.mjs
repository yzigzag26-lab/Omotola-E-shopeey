#!/usr/bin/env node
/**
 * Regenerates the two SQL seed artefacts from the single source of truth,
 * supabase/seed/demo-catalog.json:
 *
 *   supabase/seed/demo-catalog.sql  readable, idempotent, for manual SQL Editor runs
 *   supabase/seed/seed-apply.sql    compact jsonb_populate_recordset form used by `npm run seed`
 *
 * Run this after editing the JSON so the three stay in sync.
 *   node scripts/generate-seed-sql.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SEED_DIR = path.join(ROOT, "supabase/seed");
const catalog = JSON.parse(await readFile(path.join(SEED_DIR, "demo-catalog.json"), "utf8"));

const q = (value) => {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replaceAll("'", "''")}'`;
};

const productImageRows = catalog.products.flatMap((product, productIndex) =>
  product.images.map((image, index) => ({
    id: image.id,
    product_id: product.id,
    storage_path: null,
    image_url: `/products/${image.file}.jpg`,
    image_url_thumb: `/products/${image.file}-thumb.jpg`,
    role: image.role,
    alt_text: image.alt,
    display_order: index,
    width: 1600,
    height: 2000,
    _productIndex: productIndex,
  })),
);

const variantRows = catalog.products.flatMap((product) =>
  product.variants.map((variant, index) => ({
    product_id: product.id,
    kind: variant.kind,
    value: variant.value,
    display_order: index,
    is_available: true,
  })),
);

/* ---------------------------------------------------------------- readable */

const lines = [
  "-- Demo catalogue seed (idempotent). Prices are illustrative demo prices in kobo.",
  "-- Generated by scripts/generate-seed-sql.mjs — edit demo-catalog.json, then regenerate.",
  "begin;",
];

for (const category of catalog.categories) {
  lines.push(
    `insert into public.categories (id,name,slug,description,display_order,is_active) values (` +
      [category.id, category.name, category.slug, category.description, category.display_order, category.is_active]
        .map(q)
        .join(",") +
      `) on conflict (slug) do update set name = excluded.name, description = excluded.description, display_order = excluded.display_order, is_active = excluded.is_active;`,
  );
}

for (const product of catalog.products) {
  lines.push(
    `insert into public.products (id,name,slug,description,category_id,price_kobo,currency,availability,status,is_featured,seo_title,seo_description) values (` +
      [
        product.id,
        product.name,
        product.slug,
        product.description,
        product.category_id,
        product.price_kobo,
        "NGN",
      ]
        .map(q)
        .join(",") +
      `,'${product.availability}'::public.availability_status,'${product.status}'::public.publication_status,` +
      `${q(product.is_featured)},${q(product.seo_title)},${q(product.seo_description)}) ` +
      `on conflict (slug) do update set name = excluded.name, description = excluded.description, category_id = excluded.category_id, price_kobo = excluded.price_kobo, availability = excluded.availability, status = excluded.status, is_featured = excluded.is_featured, seo_title = excluded.seo_title, seo_description = excluded.seo_description;`,
  );
}

for (const image of productImageRows) {
  lines.push(
    `insert into public.product_images (id,product_id,storage_path,image_url,image_url_thumb,role,alt_text,display_order,width,height) values (` +
      [
        image.id,
        `(select id from public.products where slug = ${q(catalog.products[image._productIndex].slug)})`,
        null,
        image.image_url,
        image.image_url_thumb,
        `'${image.role}'::public.image_role`,
        image.alt_text,
        image.display_order,
        image.width,
        image.height,
      ].join(",") +
      `) on conflict (id) do update set image_url = excluded.image_url, image_url_thumb = excluded.image_url_thumb, role = excluded.role, alt_text = excluded.alt_text, display_order = excluded.display_order;`,
  );
}

for (const variant of variantRows) {
  lines.push(
    `insert into public.product_variants (product_id,kind,value,display_order,is_available) values (` +
      [
        `(select id from public.products where slug = ${q(catalog.products.find((p) => p.id === variant.product_id).slug)})`,
        variant.kind,
        variant.value,
        variant.display_order,
        variant.is_available,
      ].join(",") +
      `) on conflict (product_id, kind, value) do update set display_order = excluded.display_order, is_available = excluded.is_available;`,
  );
}

lines.push(
  `insert into public.announcements (id,message,is_enabled) values (` +
    [catalog.announcement.id, catalog.announcement.message, catalog.announcement.is_enabled].map(q).join(",") +
    `) on conflict (id) do update set message = excluded.message, is_enabled = excluded.is_enabled;`,
);
lines.push("commit;");
lines.push("");

await writeFile(path.join(SEED_DIR, "demo-catalog.sql"), lines.join("\n"), "utf8");

/* ----------------------------------------------------------------- compact */

const compact = [
  "insert into public.categories (id,name,slug,description,display_order,is_active) select id,name,slug,description,display_order,is_active from jsonb_populate_recordset(null::public.categories," +
    q(JSON.stringify(catalog.categories.map(({ id, name, slug, description, display_order, is_active }) => ({ id, name, slug, description, display_order, is_active })))) +
    ") on conflict (slug) do update set name = excluded.name, description = excluded.description, display_order = excluded.display_order, is_active = excluded.is_active;",
  "insert into public.products (id,name,slug,description,category_id,price_kobo,currency,availability,status,is_featured,seo_title,seo_description) select id,name,slug,description,category_id,price_kobo,currency,availability,status,is_featured,seo_title,seo_description from jsonb_populate_recordset(null::public.products," +
    q(JSON.stringify(catalog.products.map((p) => ({ ...p, currency: "NGN", variants: undefined, images: undefined })))) +
    ") on conflict (slug) do update set name = excluded.name, description = excluded.description, category_id = excluded.category_id, price_kobo = excluded.price_kobo, availability = excluded.availability, status = excluded.status, is_featured = excluded.is_featured, seo_title = excluded.seo_title, seo_description = excluded.seo_description;",
  "insert into public.product_images (id,product_id,storage_path,image_url,image_url_thumb,role,alt_text,display_order,width,height) select id,product_id,storage_path,image_url,image_url_thumb,role,alt_text,display_order,width,height from jsonb_populate_recordset(null::public.product_images," +
    q(JSON.stringify(productImageRows.map(({ _productIndex, ...row }) => row))) +
    ") on conflict (id) do update set image_url = excluded.image_url, image_url_thumb = excluded.image_url_thumb, role = excluded.role, alt_text = excluded.alt_text, display_order = excluded.display_order;",
  "insert into public.product_variants (product_id,kind,value,display_order,is_available) select product_id,kind,value,display_order,is_available from jsonb_populate_recordset(null::public.product_variants," +
    q(JSON.stringify(variantRows)) +
    ") on conflict (product_id, kind, value) do update set display_order = excluded.display_order, is_available = excluded.is_available;",
  "insert into public.announcements (id,message,is_enabled) select id,message,is_enabled from jsonb_populate_recordset(null::public.announcements," +
    q(JSON.stringify([catalog.announcement])) +
    ") on conflict (id) do update set message = excluded.message, is_enabled = excluded.is_enabled;",
  "select (select count(*) from public.categories) as categories, (select count(*) from public.products) as products, (select count(*) from public.product_images) as images, (select count(*) from public.product_variants) as variants, (select count(*) from public.announcements where is_enabled) as announcements;",
  "",
];

await writeFile(path.join(SEED_DIR, "seed-apply.sql"), compact.join("\n"), "utf8");

console.log(
  `generated: ${catalog.categories.length} categories, ${catalog.products.length} products, ` +
    `${productImageRows.length} images, ${variantRows.length} variants, 1 announcement`,
);
